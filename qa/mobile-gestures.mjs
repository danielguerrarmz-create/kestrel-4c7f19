import { launch } from './lib.mjs';
const {browser,page}=await launch({width:390,height:844,mobile:true});
await page.goto('http://127.0.0.1:5173/gallery',{waitUntil:'networkidle0'});
await page.screenshot({path:'qa/shots/mobile-redesign/_gallery.png'});
await page.locator('button[aria-label="Enlarge Wisteria walk"]').click();
const cdp=await page.createCDPSession();
const touch=async(type,pts)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:pts.map(([x,y],id)=>({x,y,id}))});
await touch('touchStart',[[145,350],[245,350]]);
for(let i=1;i<=8;i++) await touch('touchMove',[[145-i*8,350],[245+i*8,350]]);
await touch('touchEnd',[]);
const pinch=await page.$eval('.viewer-canvas img',el=>el.style.transform);
if(pinch.includes('scale(1)')) throw Error('Pinch did not zoom');
await page.locator('button[aria-label="Reset zoom"]').click();
await page.touchscreen.tap(195,350);
await page.touchscreen.tap(195,350);
await page.waitForFunction(()=>document.querySelector('.viewer-canvas img').style.transform.includes('scale(2.5)'));
await touch('touchStart',[[195,350]]);
await touch('touchMove',[[260,350]]);
await touch('touchEnd',[]);
const pan=await page.$eval('.viewer-canvas img',el=>el.style.transform);
if(pan.includes('translate(0px, 0px)')) throw Error('Pan did not move');
await page.locator('button[aria-label="Reset zoom"]').click();
await touch('touchStart',[[300,400]]);
for(let i=1;i<=8;i++) await touch('touchMove',[[300-i*24,400]]);
await touch('touchEnd',[]);
await page.waitForFunction(()=>document.querySelector('.viewer-details > p').textContent==='Walled garden');
await page.locator('button[aria-label="Close image viewer"]').click();
const focus=await page.evaluate(()=>document.activeElement?.getAttribute('aria-label'));
if(focus!=='Enlarge Wisteria walk') throw Error('Focus not restored');
await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle0'});
await page.$eval('.mobile-image-rail',el=>el.scrollIntoView());
await new Promise(r=>setTimeout(r,400));
await page.screenshot({path:'qa/shots/mobile-redesign/home-rail.png'});
const rail=await page.$eval('.mobile-image-rail',el=>({snap:getComputedStyle(el).scrollSnapType,width:el.clientWidth,scrollWidth:el.scrollWidth}));
if(rail.snap!=='x mandatory'||rail.scrollWidth<=rail.width) throw Error('Rail does not snap/scroll');
console.log({pinch,swipe:'passed',focus,rail});
await browser.close();
